function 오류보이기(예외) {
  console.error(예외);
  요소.급수버튼줄.textContent = "";
  요소.오류.hidden = false;
  요소.오류.textContent = "";

  const 첫줄 = document.createElement("b");
  첫줄.textContent = "단어 데이터를 읽지 못했어요 😢";
  const 설명 = document.createElement("p");
  설명.style.margin = "6px 0 0";
  설명.textContent = `${예외.message} 파일을 그냥 두 번 눌러 열면(file://) 브라우저가 데이터 읽기를 막습니다. 아래처럼 작은 서버로 띄워 주세요.`;
  const 명령 = document.createElement("code");
  명령.textContent = "python -m http.server 8765 --directory jlpt_version";

  요소.오류.append(첫줄, 설명, 명령);
  화면보이기("급수");
}

async function 앱시작() {
  이벤트달기();
  토글모양갱신();

  try {
    await 불러오기();
  } catch (예외) {
    오류보이기(예외);
    return;
  }

  급수화면으로();
}

앱시작();
