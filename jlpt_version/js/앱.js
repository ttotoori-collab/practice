/** 배열을 제자리에서 섞는다 (피셔-예이츠). */
function 섞기(배열) {
  const 새배열 = [...배열];
  for (let 칸 = 새배열.length - 1; 칸 > 0; 칸 -= 1) {
    const 뽑은칸 = Math.floor(Math.random() * (칸 + 1));
    [새배열[칸], 새배열[뽑은칸]] = [새배열[뽑은칸], 새배열[칸]];
  }
  return 새배열;
}

function 화면보이기(이름) {
  요소.급수화면.hidden = 이름 !== "급수";
  요소.카드화면.hidden = 이름 !== "카드";
  요소.완료화면.hidden = 이름 !== "완료";
}

/* ── 공부시간 시계 ────────────────────────────────── */

function 시간글갱신() {
  요소.상태시간.textContent = `공부시간 ${시간글(쌓인초)}`;
}

function 똑딱() {
  // 다른 탭을 보고 있는 동안은 공부한 것이 아니니 세지 않는다.
  if (document.hidden || !현재급수) return;

  쌓인초 += 1;
  시간글갱신();
  if (쌓인초 % 10 === 0) 기록.공부시간저장(현재급수, 쌓인초);
}

function 시계시작() {
  if (시계 === null) 시계 = setInterval(똑딱, 1000);
}

function 시계멈춤() {
  if (시계 !== null) {
    clearInterval(시계);
    시계 = null;
  }
  if (현재급수) 기록.공부시간저장(현재급수, 쌓인초);
}

/* ── 진행 표시 ────────────────────────────────────── */

function 진행갱신() {
  if (!현재급수) {
    요소.상태급수.textContent = "N–";
    요소.상태진행.textContent = "0/0";
    return;
  }

  const 모든단어 = 급수단어(현재급수);
  const 외운것 = 기록.외운단어(현재급수);
  // words.json 에서 단어를 뺐을 수도 있으니 지금 있는 단어만 센다.
  const 외운개수 = 모든단어.filter((하나) => 외운것.has(하나.식별자)).length;
  const 전체개수 = 모든단어.length;
  const 비율 = 전체개수 === 0 ? 0 : Math.round((외운개수 / 전체개수) * 100);

  요소.진행글.textContent = `외운 단어 ${외운개수} / ${전체개수}`;
  요소.진행막대안.style.width = `${비율}%`;
  요소.회차글.textContent = `${회차번호}회차 · 남은 카드 ${이번회차.length + (현재단어 ? 1 : 0)}장`;

  요소.상태급수.textContent = 현재급수;
  요소.상태진행.textContent = `${외운개수}/${전체개수}`;
}

/* ── 급수 선택 화면 ──────────────────────────────── */

function 급수버튼채우기() {
  요소.급수버튼줄.textContent = "";

  const 색깔 = ["핑크", "하늘", "라벤더"];
  있는급수().forEach((급수, 순서) => {
    const 모든단어 = 급수단어(급수);
    const 외운것 = 기록.외운단어(급수);
    const 외운개수 = 모든단어.filter((하나) => 외운것.has(하나.식별자)).length;

    const 버튼 = document.createElement("button");
    버튼.type = "button";
    버튼.className = `젤리 급수버튼 ${색깔[순서 % 색깔.length]}`;
    버튼.append(document.createTextNode(급수));

    const 설명 = document.createElement("span");
    설명.className = "급수버튼설명";
    설명.textContent = `${급수소개[급수] ?? "단어 모음"} · ${모든단어.length}개 중 ${외운개수}개 외움`;
    버튼.append(설명);

    버튼.addEventListener("click", () => 급수시작(급수));
    요소.급수버튼줄.append(버튼);
  });
}

function 급수화면으로() {
  시계멈춤();
  현재급수 = null;
  현재단어 = null;
  이번회차 = [];
  다음회차 = [];
  회차번호 = 1;

  급수버튼채우기();
  진행갱신();
  요소.상태시간.textContent = "공부시간 00:00";
  화면보이기("급수");
}

/* ── 카드 화면 ────────────────────────────────────── */

function 급수시작(급수) {
  현재급수 = 급수;
  쌓인초 = 기록.공부시간(급수);
  시간글갱신();
  시계시작();

  const 외운것 = 기록.외운단어(급수);
  const 아직모르는것 = 급수단어(급수).filter((하나) => !외운것.has(하나.식별자));

  회차번호 = 1;
  다음회차 = [];
  이번회차 = 섞기(아직모르는것);
  현재단어 = null;

  if (이번회차.length === 0) {
    완료화면으로();
    return;
  }

  화면보이기("카드");
  다음단어();
}

function 다음단어() {
  if (이번회차.length === 0) {
    if (다음회차.length === 0) {
      완료화면으로();
      return;
    }
    // 한 바퀴를 다 돌았다. "공부하겠음" 한 단어들로 다음 회차를 시작한다.
    회차번호 += 1;
    이번회차 = 섞기(다음회차);
    다음회차 = [];
  }

  현재단어 = 이번회차.shift();
  카드그리기(요소, 현재단어, 설정);
  진행갱신();
}

function 완료화면으로() {
  현재단어 = null;
  const 전체개수 = 현재급수 ? 급수단어(현재급수).length : 0;
  요소.완료쪽지.textContent = `${현재급수} 단어 ${전체개수}개를 ${시간글(쌓인초)} 만에 다 외웠어요 ♡`;
  진행갱신();
  화면보이기("완료");
}

/* ── 버튼 켜짐 상태 ─────────────────────────────── */

function 토글모양갱신() {
  for (const 짝 of 토글짝) {
    짝.버튼.setAttribute("aria-pressed", String(Boolean(설정[짝.이름])));
  }
}

function 토글누름(이름) {
  설정 = { ...설정, [이름]: !설정[이름] };
  기록.설정바꾸기(이름, 설정[이름]);
  토글모양갱신();
  if (현재단어) 카드그리기(요소, 현재단어, 설정);
}

/* ── 이벤트 묶기 ──────────────────────────────────── */

function 이벤트달기() {
  창접기달기(요소.창, 요소.최소화버튼);
  닫기장난달기(요소.닫기버튼, 요소.쪽지);

  for (const 짝 of 토글짝) {
    짝.버튼.addEventListener("click", () => 토글누름(짝.이름));
  }

  요소.공부하겠음버튼.addEventListener("click", () => {
    if (!현재단어) return;
    다음회차.push(현재단어);   // 이번 회차가 끝나면 다시 나온다
    다음단어();
  });

  요소.알고있음버튼.addEventListener("click", () => {
    if (!현재단어) return;
    기록.외움표시(현재급수, 현재단어.식별자);
    다음단어();
  });

  요소.급수선택버튼.addEventListener("click", 급수화면으로);
  요소.다른급수버튼.addEventListener("click", 급수화면으로);

  요소.다시외우기버튼.addEventListener("click", () => {
    // 외운 표시만 지우고 공부한 시간은 남겨 둔다.
    기록.급수초기화(현재급수, { 시간도: false });
    급수시작(현재급수);
  });

  요소.섞기버튼.addEventListener("click", () => {
    if (!현재단어) {
      쪽지보이기(요소.쪽지, "단어 카드를 보는 중에만 섞을 수 있어요 🔀");
      return;
    }
    이번회차 = 섞기([현재단어, ...이번회차]);
    현재단어 = null;
    다음단어();
    쪽지보이기(요소.쪽지, "이번 회차를 다시 섞었어요 🔀");
  });

  요소.도움말버튼.addEventListener("click", () => {
    const 보임 = 요소.도움말.hidden;
    요소.도움말.hidden = !보임;
    요소.도움말버튼.setAttribute("aria-expanded", String(보임));
  });

  요소.초기화버튼.addEventListener("click", () => {
    쪽지감추기(요소.쪽지);
    요소.확인판.hidden = false;
    요소.이급수초기화버튼.hidden = !현재급수;
  });

  요소.초기화취소버튼.addEventListener("click", () => { 요소.확인판.hidden = true; });

  요소.이급수초기화버튼.addEventListener("click", () => {
    const 지운급수 = 현재급수;
    요소.확인판.hidden = true;
    if (!지운급수) return;

    기록.급수초기화(지운급수);
    쌓인초 = 0;
    시간글갱신();
    급수시작(지운급수);
    쪽지보이기(요소.쪽지, `${지운급수} 기록을 지웠어요 🧹`);
  });

  요소.전체초기화버튼.addEventListener("click", () => {
    요소.확인판.hidden = true;
    기록.전체초기화();
    쌓인초 = 0;
    급수화면으로();
    쪽지보이기(요소.쪽지, "모든 기록을 지웠어요. 처음부터 해 봐요! 🧹");
  });

  // 탭을 닫거나 숨길 때 공부시간을 흘리지 않게 저장한다.
  window.addEventListener("pagehide", () => { if (현재급수) 기록.공부시간저장(현재급수, 쌓인초); });
  document.addEventListener("visibilitychange", () => {
    if (document.hidden && 현재급수) 기록.공부시간저장(현재급수, 쌓인초);
  });
}

