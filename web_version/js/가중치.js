/**
 * 학습된 가중치를 내려받아 이름으로 찾아 쓸 수 있게 정리하는 모듈.
 *
 * 형식은 도구/가중치_내보내기.py 가 만든다.
 *   모델/mnist_cnn.json  텐서 이름·모양·시작바이트 목록
 *   모델/mnist_cnn.bin   Float32 리틀엔디언 본문 (텐서를 C 순서로 이어 붙인 것)
 *
 * 외부 라이브러리를 쓰지 않으므로 PyTorch 파일을 직접 읽지 못한다. 그래서
 * 위 두 파일로 한 번 변환해 두고, 여기서는 fetch 로 받아 잘라 쓰기만 한다.
 */

/** 모델이 반드시 가지고 있어야 하는 텐서와 그 모양. model.py 의 구조와 같아야 한다. */
export const 기대하는모양 = {
  "합성곱1.weight": [32, 1, 3, 3],
  "합성곱1.bias": [32],
  "합성곱2.weight": [64, 32, 3, 3],
  "합성곱2.bias": [64],
  "전결합1.weight": [128, 3136],
  "전결합1.bias": [128],
  "전결합2.weight": [10, 128],
  "전결합2.bias": [10],
};

/**
 * 가중치를 내려받아 {텐서이름: {모양, 값}} 형태로 돌려준다.
 *
 * 값은 Float32Array 이고, 원본 텐서를 C 순서(마지막 차원이 가장 빠르게 변함)로
 * 평탄화한 것이다. 예를 들어 합성곱1.weight 의 (출력채널, 입력채널, 행, 열) 은
 * 색인 ((출력채널*입력채널 + 입력채널)*3 + 행)*3 + 열 에 놓인다.
 *
 * @param {string} 기준경로 모델 폴더의 경로. 끝에 슬래시를 붙이지 않는다.
 */
export async function 가중치_불러오기(기준경로 = "모델") {
  const 목록응답 = await fetch(`${기준경로}/mnist_cnn.json`);
  if (!목록응답.ok) {
    throw new Error(
      `가중치 목록을 받지 못했습니다 (${목록응답.status}). ` +
      "도구/가중치_내보내기.py 를 먼저 실행했는지 확인해 주세요."
    );
  }
  const 목록 = await 목록응답.json();

  const 본문응답 = await fetch(`${기준경로}/${목록.본문파일}`);
  if (!본문응답.ok) {
    throw new Error(`가중치 본문을 받지 못했습니다 (${본문응답.status}).`);
  }
  const 버퍼 = await 본문응답.arrayBuffer();

  if (버퍼.byteLength !== 목록.전체바이트) {
    throw new Error(
      `가중치 크기가 목록과 다릅니다: 받은 ${버퍼.byteLength}바이트, ` +
      `기대한 ${목록.전체바이트}바이트`
    );
  }

  const 가중치 = {};
  for (const 텐서 of 목록.텐서) {
    // Float32Array 는 리틀엔디언 환경에서 바이트를 그대로 해석한다.
    // 사실상 모든 브라우저가 리틀엔디언이므로 내보낸 순서와 일치한다.
    가중치[텐서.이름] = {
      모양: 텐서.모양,
      값: new Float32Array(버퍼, 텐서.시작바이트, 텐서.개수),
    };
  }

  모양_검사(가중치);
  return 가중치;
}

/**
 * 받은 가중치가 js/신경망.js 가 가정하는 구조와 맞는지 확인한다.
 *
 * 모양이 어긋난 채 추론하면 오류 없이 엉뚱한 숫자가 나오기 때문에,
 * 여기서 먼저 걸러 내는 편이 원인을 찾기 쉽다.
 */
export function 모양_검사(가중치) {
  for (const [이름, 기대] of Object.entries(기대하는모양)) {
    const 텐서 = 가중치[이름];
    if (!텐서) {
      throw new Error(`가중치에 '${이름}' 텐서가 없습니다.`);
    }
    const 실제 = 텐서.모양;
    if (실제.length !== 기대.length || 실제.some((값, 축) => 값 !== 기대[축])) {
      throw new Error(
        `'${이름}' 의 모양이 다릅니다: 받은 [${실제}], 기대한 [${기대}]. ` +
        "model.py 의 구조를 바꿨다면 가중치_내보내기.py 와 신경망.js 도 함께 고쳐야 합니다."
      );
    }
  }
}
