/**
 * 순수 자바스크립트 CNN 추론 엔진.
 *
 * desktop_version/model.py 의 숫자인식CNN 순전파를 그대로 옮긴 것이다.
 *   합성곱1(1→32, 3x3, 여백1) → 렐루 → 최대풀링2 → (32, 14, 14)
 *   합성곱2(32→64, 3x3, 여백1) → 렐루 → 최대풀링2 → (64, 7, 7)
 *   평탄화(3136) → 전결합1(→128) → 렐루 → 전결합2(→10) → 로그소프트맥스
 *
 * 드롭아웃은 평가 모드에서 항등 함수이므로 구현하지 않는다.
 *
 * 이 모듈은 브라우저 API 를 쓰지 않는 순수 함수만 담는다. 그래서 화면 없이도
 * 값만으로 검증할 수 있다.
 *
 * 특징맵은 모두 1차원 Float32Array 에 (채널, 행, 열) 순서로 담는다.
 *   색인 = 채널*(높이*너비) + 행*너비 + 열
 * PyTorch 의 flatten(1) 과 같은 순서이며, 이 순서가 어긋나면 전결합1 의
 * 가중치와 맞지 않아 오류 없이 엉뚱한 답이 나온다.
 */

/**
 * 2차원 합성곱. stride 는 1, 여백은 0 으로 채운다 (PyTorch 기본값과 같다).
 *
 * @param {Float32Array} 입력 (입력채널, 높이, 너비)
 * @param {Float32Array} 가중치 (출력채널, 입력채널, 커널, 커널)
 * @param {Float32Array} 편향 (출력채널)
 * @returns {Float32Array} (출력채널, 높이, 너비) — 여백 1, 커널 3 이라 크기가 유지된다
 */
export function 합성곱(입력, 높이, 너비, 입력채널, 출력채널, 가중치, 편향, 커널, 여백) {
  const 면적 = 높이 * 너비;
  const 출력 = new Float32Array(출력채널 * 면적);

  for (let 출채 = 0; 출채 < 출력채널; 출채 += 1) {
    const 출력밑 = 출채 * 면적;
    const 편향값 = 편향[출채];

    for (let 행 = 0; 행 < 높이; 행 += 1) {
      for (let 열 = 0; 열 < 너비; 열 += 1) {
        let 합 = 편향값;

        for (let 입채 = 0; 입채 < 입력채널; 입채 += 1) {
          const 입력밑 = 입채 * 면적;
          const 커널밑 = (출채 * 입력채널 + 입채) * 커널 * 커널;

          for (let 커행 = 0; 커행 < 커널; 커행 += 1) {
            const 읽을행 = 행 + 커행 - 여백;
            if (읽을행 < 0 || 읽을행 >= 높이) continue;   // 여백은 0 이므로 건너뛴다

            for (let 커열 = 0; 커열 < 커널; 커열 += 1) {
              const 읽을열 = 열 + 커열 - 여백;
              if (읽을열 < 0 || 읽을열 >= 너비) continue;

              합 += 입력[입력밑 + 읽을행 * 너비 + 읽을열]
                  * 가중치[커널밑 + 커행 * 커널 + 커열];
            }
          }
        }
        출력[출력밑 + 행 * 너비 + 열] = 합;
      }
    }
  }
  return 출력;
}

/** 제자리에서 렐루를 적용한다 (음수를 0 으로). */
export function 렐루(배열) {
  for (let 색인 = 0; 색인 < 배열.length; 색인 += 1) {
    if (배열[색인] < 0) 배열[색인] = 0;
  }
  return 배열;
}

/**
 * 최대풀링. 창 크기와 보폭이 같다 (PyTorch max_pool2d(x, 크기) 와 같은 동작).
 * 홀수 크기는 PyTorch 처럼 남는 줄을 버린다.
 */
export function 최대풀링(입력, 채널, 높이, 너비, 창) {
  const 새높이 = Math.floor(높이 / 창);
  const 새너비 = Math.floor(너비 / 창);
  const 출력 = new Float32Array(채널 * 새높이 * 새너비);

  for (let 채 = 0; 채 < 채널; 채 += 1) {
    const 입력밑 = 채 * 높이 * 너비;
    const 출력밑 = 채 * 새높이 * 새너비;

    for (let 행 = 0; 행 < 새높이; 행 += 1) {
      for (let 열 = 0; 열 < 새너비; 열 += 1) {
        let 최대 = -Infinity;
        for (let 창행 = 0; 창행 < 창; 창행 += 1) {
          for (let 창열 = 0; 창열 < 창; 창열 += 1) {
            const 값 = 입력[입력밑 + (행 * 창 + 창행) * 너비 + (열 * 창 + 창열)];
            if (값 > 최대) 최대 = 값;
          }
        }
        출력[출력밑 + 행 * 새너비 + 열] = 최대;
      }
    }
  }
  return 출력;
}

/**
 * 완전연결층. PyTorch Linear 와 같이 가중치는 (출력수, 입력수) 순서다.
 */
export function 전결합(입력, 가중치, 편향, 입력수, 출력수) {
  const 출력 = new Float32Array(출력수);
  for (let 출 = 0; 출 < 출력수; 출 += 1) {
    const 밑 = 출 * 입력수;
    let 합 = 편향[출];
    for (let 입 = 0; 입 < 입력수; 입 += 1) {
      합 += 가중치[밑 + 입] * 입력[입];
    }
    출력[출] = 합;
  }
  return 출력;
}

/**
 * 로그 소프트맥스. 최댓값을 먼저 빼서 exp 가 넘치지 않게 한다.
 * model.py 가 log_softmax 를 돌려주므로 여기서도 같은 값을 만든다.
 */
export function 로그소프트맥스(배열) {
  let 최대 = -Infinity;
  for (const 값 of 배열) if (값 > 최대) 최대 = 값;

  let 합 = 0;
  for (const 값 of 배열) 합 += Math.exp(값 - 최대);

  const 로그합 = Math.log(합);
  const 출력 = new Float32Array(배열.length);
  for (let 색인 = 0; 색인 < 배열.length; 색인 += 1) {
    출력[색인] = 배열[색인] - 최대 - 로그합;
  }
  return 출력;
}

/**
 * 28x28 정규화된 입력 하나를 넣어 0~9 각각의 확률을 얻는다.
 *
 * app.py 가 torch.exp(log_softmax) 로 확률을 구하는 것과 같은 계산이다.
 *
 * @param {Float32Array} 입력 길이 784. (값/255 - 평균) / 표준편차 로 정규화된 상태
 * @param {object} 가중치 가중치.js 의 가중치_불러오기() 결과
 * @returns {Float32Array} 길이 10, 합이 1인 확률
 */
export function 추론(입력, 가중치) {
  if (입력.length !== 28 * 28) {
    throw new Error(`입력 길이가 784 가 아닙니다: ${입력.length}`);
  }

  // 합성곱1 → 렐루 → 최대풀링 : (1,28,28) → (32,14,14)
  let 특징 = 합성곱(입력, 28, 28, 1, 32,
                    가중치["합성곱1.weight"].값, 가중치["합성곱1.bias"].값, 3, 1);
  렐루(특징);
  특징 = 최대풀링(특징, 32, 28, 28, 2);

  // 합성곱2 → 렐루 → 최대풀링 : (32,14,14) → (64,7,7)
  특징 = 합성곱(특징, 14, 14, 32, 64,
                가중치["합성곱2.weight"].값, 가중치["합성곱2.bias"].값, 3, 1);
  렐루(특징);
  특징 = 최대풀링(특징, 64, 14, 14, 2);

  // 특징은 이미 (채널, 행, 열) 순서로 평탄하므로 따로 펼칠 필요가 없다. 길이 3136.
  let 출력 = 전결합(특징, 가중치["전결합1.weight"].값, 가중치["전결합1.bias"].값, 3136, 128);
  렐루(출력);
  출력 = 전결합(출력, 가중치["전결합2.weight"].값, 가중치["전결합2.bias"].값, 128, 10);

  const 로그확률 = 로그소프트맥스(출력);
  const 확률 = new Float32Array(10);
  for (let 숫자 = 0; 숫자 < 10; 숫자 += 1) 확률[숫자] = Math.exp(로그확률[숫자]);
  return 확률;
}
